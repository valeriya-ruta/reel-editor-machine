HEAD = """{title}
{rule}

ЯК СТАВИТИ
  Формат .webm з прозорим фоном. В Edits прозоре читається як чорне —
  вмикай режим накладання LIGHTEN, і чорне зникне.
  Все відцентроване по кадру, став де завгодно.

"""


def main():
    if os.path.isdir(DST):
        shutil.rmtree(DST)
    os.makedirs(DST)

    master = ["АНІМАЦІЇ ДО РІЛСІВ", "=" * 60, "",
              "Кожна папка — один рілс. Файли пронумеровані в тому порядку,",
              "в якому вони йдуть у твоєму сценарії.",
              "",
              "В кожній папці лежить _КОЛИ-СТАВИТИ.txt — там написано,",
              "на яких саме словах ставити кожну анімацію.",
              "",
              "ФОРМАТ: .webm з альфою. В Edits став LIGHTEN.",
              "ВИНЯТОК: 05_three-categories_FULLSCREEN.mp4 — повний екран,",
              "         ставиться ЗАМІСТЬ відео, не поверх.",
              "",
              "Логотипів ніде немає — додаєш сама.",
              "", "=" * 60, ""]

    for folder, title, items in REELS:
        d = os.path.join(DST, folder)
        os.makedirs(d)

        lines = [HEAD.format(title=title, rule="=" * len(title))]
        master.append(title)

        for num, old, new, cue, note in items:
            ext = ".mp4" if old.endswith(".mp4") else ".webm"
            src = os.path.join(SRC, old if old.endswith(".mp4") else old + ".webm")
            dst = os.path.join(d, new + ext)
            if os.path.exists(src):
                shutil.copy2(src, dst)
            else:
                print("MISSING:", src)

            lines.append("-" * 62)
            lines.append(num + "   " + new + ext)
            lines.append("")
            lines.append("     СЛОВА:  " + cue)
            lines.append("")
            lines.append("     ЯК:     " + note)
            lines.append("")
            master.append("    " + num + "  " + new + ext)

        lines.append("-" * 62)
        io.open(os.path.join(d, "_КОЛИ-СТАВИТИ.txt"), "w", encoding="utf-8").write("\n".join(lines))
        master.append("")

    io.open(os.path.join(DST, "ПОЧНИ-ЗВІДСИ.txt"), "w", encoding="utf-8").write("\n".join(master))
    print("done ->", DST)


if __name__ == "__main__":
    main()
