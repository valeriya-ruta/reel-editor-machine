def norm(w):
    return re.sub(u"[^\\w]", "", w.lower()).replace(u"ї", u"і").replace(u"й", u"и").replace(u"є", u"е")
caps = []
for u in U:
    mine = T[u["k"]].split()
    ws = u["words"] or [{"w": "", "s": u["a"], "e": u["b"]}]
    sm = difflib.SequenceMatcher(None, [norm(x) for x in mine], [norm(x["w"]) for x in ws], autojunk=False)
    st = [None] * len(mine)
    for blk in sm.get_matching_blocks():
        for j in range(blk.size):
            st[blk.a + j] = ws[blk.b + j]["s"]
    if st[0] is None: st[0] = ws[0]["s"]
    end = ws[-1]["e"]
    i = 0
    while i < len(mine):
        if st[i] is None:
            j = i
            while j < len(mine) and st[j] is None: j += 1
            lo, hi = st[i - 1], (st[j] if j < len(mine) else end)
            tot = sum(len(x) for x in mine[i - 1:j]); acc = len(mine[i - 1])
            for q in range(i, j):
                st[q] = lo + (hi - lo) * acc / float(tot); acc += len(mine[q])
            i = j
        i += 1
    for q, x in enumerate(mine):
        caps.append({"w": x, "s": round(st[q], 3), "e": round(end, 3)})
caps.sort(key=lambda c: c["s"])
for c, n in zip(caps, caps[1:]):
    if n["s"] < c["s"] + 0.12: n["s"] = round(c["s"] + 0.12, 3)
for c, n in zip(caps, caps[1:]):
    c["e"] = round(min(max(c["s"] + 0.12, n["s"] - 0.085), n["s"] - 0.02, c["e"] + 0.3), 3)
io.open("captions.json", "w", encoding="utf-8").write(json.dumps({"words": caps}, ensure_ascii=False, indent=0))
